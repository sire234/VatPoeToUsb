os.environ.setdefault('KICAD10_FOOTPRINT_DIR', r'C:\Program Files\KiCad\10.0\share\kicad\footprints')
os.environ.setdefault('KICAD_FOOTPRINT_DIR',   r'C:\Program Files\KiCad\10.0\share\kicad\footprints')
from skidl import *

PROJECT_ROOT = r'C:\Users\simon\Documents\Projects\Test\PoeToUSB'
PROJECT_LIBS = PROJECT_ROOT + r'\libs'
if PROJECT_LIBS not in lib_search_paths[KICAD]:
    lib_search_paths[KICAD].append(PROJECT_LIBS)
# Footprint search: KiCad 10 stock footprints + project footprint library.
for _fp in (r'C:\Program Files\KiCad\10.0\share\kicad\footprints',
            PROJECT_ROOT + r'\footprints\poe_usb_hid_bridge.pretty'):
    if _fp not in footprint_search_paths[KICAD]:
        footprint_search_paths[KICAD].append(_fp)

from .ethernet_magjack import ethernet_magjack
from .poe_pd_module import poe_pd_module
from .ldo_3v3 import ldo_3v3
from .mcu_w55rp20 import mcu_w55rp20
from .usb_host_port import usb_host_port
from .status_led import status_led

# ---- Power nets ----
V5 = Net('+5V');       V5.drive = POWER
V3V3 = Net('+3V3');    V3V3.drive = POWER
V3V3A = Net('+3V3A');  V3V3A.drive = POWER   # passive, fed from +3V3 via FB2
GND = Net('GND');      GND.drive = POWER
# VDD_POE / VSS / +5V_RAW are internal nets of poe_pd_module (Rev 4).

# ---- PoE PSE pair nets ----
PSE_CT12 = Net('PSE_CT12')
PSE_CT36 = Net('PSE_CT36')
PSE_SP45 = Net('PSE_SP45')
PSE_SP78 = Net('PSE_SP78')

# ---- Ethernet nets ----
ETH_TXP = Net('ETH_TXP')
ETH_TXN = Net('ETH_TXN')
ETH_RXP = Net('ETH_RXP')
ETH_RXN = Net('ETH_RXN')
# Rev 4b: ETH_LED_LINK_N / ETH_LED_ACT_N removed (MagJack LEDs not driven).
# RX pair is driven by the remote PHY through the passive MagJack and only
# received by the W5500: no pin on the board is an output -> skip "no driver" ERC
# on these two nets only (ERC stays enabled globally).
ETH_RXP.do_erc = False
ETH_RXN.do_erc = False

# ---- USB / control nets ----
USB_DP_MCU = Net('USB_DP_MCU')
USB_DM_MCU = Net('USB_DM_MCU')
USB_EN = Net('USB_EN')
# Rev 4d: USB_OC_N removed (TPS2553 FAULT unconnected, GPIO18 free).
VBUS_SENSE = Net('VBUS_SENSE')
LED_DIN = Net('LED_DIN')   # GPIO28 -> green status LED D11 via R38 (Rev 4f; Rev 4b-4e: WS2812B data)
# Rev 4g: MagJack LEDs driven again by the W5500 LED outputs (active low)
ETH_LED_LINK_N = Net('ETH_LED_LINK_N')   # U5.37 LINKLED -> J1.14 green cathode
ETH_LED_ACT_N = Net('ETH_LED_ACT_N')     # U5.39 ACTLED  -> J1.12 yellow cathode

# ---- Instantiate blocks ----
ethernet_magjack(pse_ct12=PSE_CT12, pse_ct36=PSE_CT36, pse_sp45=PSE_SP45, pse_sp78=PSE_SP78,
                 eth_txp=ETH_TXP, eth_txn=ETH_TXN, eth_rxp=ETH_RXP, eth_rxn=ETH_RXN,
                 v3v3a=V3V3A, v3v3=V3V3, gnd=GND,
                 eth_led_link_n=ETH_LED_LINK_N, eth_led_act_n=ETH_LED_ACT_N)
poe_pd_module(pse_ct12=PSE_CT12, pse_ct36=PSE_CT36, pse_sp45=PSE_SP45, pse_sp78=PSE_SP78,
              v5=V5, gnd=GND)
ldo_3v3(v5=V5, v3v3=V3V3, gnd=GND)
mcu_w55rp20(v3v3=V3V3, v3v3a=V3V3A, gnd=GND,
            eth_txp=ETH_TXP, eth_txn=ETH_TXN, eth_rxp=ETH_RXP, eth_rxn=ETH_RXN,
            usb_dp_mcu=USB_DP_MCU, usb_dm_mcu=USB_DM_MCU, usb_en=USB_EN,
            vbus_sense=VBUS_SENSE, led_din=LED_DIN,
            eth_led_link_n=ETH_LED_LINK_N, eth_led_act_n=ETH_LED_ACT_N)
usb_host_port(v5=V5, gnd=GND, usb_en=USB_EN,
              usb_dp_mcu=USB_DP_MCU, usb_dm_mcu=USB_DM_MCU, vbus_sense=VBUS_SENSE)
status_led(gnd=GND, led_din=LED_DIN)   # Rev 4f: plain green LED, active-high

if __name__ == '__main__':
    ERC()
    # Rev 4f: D11 plain green LED, C64 removed. Rev 4g: MagJack LEDs on LINKLED/ACTLED (R5/R6).
    # New file names per revision (older outputs are kept unchanged).
    generate_netlist(file_=PROJECT_ROOT + r'\outputs\poe_usb_hid_bridge_rev4g.net')
    generate_xml(file_=PROJECT_ROOT + r'\outputs\poe_usb_hid_bridge_rev4g_bom.xml')
